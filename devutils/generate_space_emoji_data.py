#!/usr/bin/env python3
"""Generate the native Space picker catalogue from Chromium and English CLDR."""

import argparse
import ast
import hashlib
import io
import json
from pathlib import Path
import re
import tokenize
import unicodedata
import xml.etree.ElementTree as ET


def catalogue(source):
    text = source.read_text()
    match = re.search(r"(?m)^export const emojiData\s*=\s*", text)
    assert match, "Missing emojiData literal"
    literal = text[match.end():].strip()
    assert literal.endswith(";"), "Unexpected catalogue suffix"
    tokens = tokenize.generate_tokens(io.StringIO(literal[:-1]).readline)
    converted = [
        token._replace(string={"true": "True", "false": "False"}.get(
            token.string, token.string))
        if token.type == tokenize.NAME else token
        for token in tokens
    ]
    groups = ast.literal_eval(tokenize.untokenize(converted))
    assert isinstance(groups, list) and len(groups) == 9
    return groups


def generate(src):
    source = src / "chrome/browser/resources/skills/emoji_data.ts"
    files = [source]
    annotations = {}
    for directory in ("annotations", "annotationsDerived"):
        for locale in ("en", "en_001"):
            path = src / f"third_party/cldr/src/common/{directory}/{locale}.xml"
            files.append(path)
            for annotation in ET.parse(path).iter("annotation"):
                entry = annotations.setdefault(annotation.attrib["cp"], {})
                key = "name" if annotation.attrib.get("type") == "tts" else "keywords"
                entry[key] = "".join(annotation.itertext())

    rows_by_emoji = {}
    categories = []
    for category, group in enumerate(catalogue(source)):
        assert isinstance(group["group"], str) and isinstance(group["emoji"], list)
        categories.append(group["group"])
        for entry in group["emoji"]:
            codepoints = entry["base"]
            assert codepoints and all(
                isinstance(cp, int) and 0 <= cp <= 0x10FFFF and not 0xD800 <= cp <= 0xDFFF
                for cp in codepoints
            )
            emoji = "".join(chr(cp) for cp in codepoints)
            metadata = annotations.get(emoji) or annotations.get(emoji.replace("\ufe0f", ""))
            assert metadata and metadata.get("name"), f"Missing CLDR name: {emoji}"
            name = metadata["name"]
            words = " ".join([
                name, metadata.get("keywords", ""),
                *entry.get("shortcodes", []), *entry.get("emoticons", []),
            ]).casefold()
            # Keep native names while accepting ordinary ASCII spellings such
            # as "sao tome" for the flag's accented English CLDR name.
            folded = "".join(c for c in unicodedata.normalize("NFKD", words)
                             if not unicodedata.combining(c))
            keywords = words if folded == words else words + " " + folded
            # The source lists a few symbols in multiple categories. Keep one
            # search result while retaining every category membership.
            previous = rows_by_emoji.get(emoji)
            mask = (previous[3] if previous else 0) | (1 << category)
            if previous and previous[2] != keywords:
                keywords = previous[2] + " " + keywords
            rows_by_emoji[emoji] = (emoji, name, keywords, mask)
    rows = list(rows_by_emoji.values())
    assert len(rows) > 1500
    digest = hashlib.sha256(b"".join(p.read_bytes() for p in files)).hexdigest()
    quote = lambda text: json.dumps(text, ensure_ascii=False)
    lines = [
        "// Generated by helium-chromium/devutils/generate_space_emoji_data.py.",
        "// Source: chrome/browser/resources/skills/emoji_data.ts (Chromium BSD).",
        "// Names/keywords: third_party/cldr/src/common/{annotations,annotationsDerived}/{en,en_001}.xml.",
        "// Unicode data copyright Unicode, Inc.; Unicode-DFS-2016, see third_party/cldr/LICENSE.",
        f"// Input SHA-256: {digest}",
        "// Regenerate from the selected Chromium checkout; do not edit by hand.",
        "constexpr std::string_view kSpaceEmojiCategories[] = {",
        *[f"    {quote(label)}," for label in categories],
        "};", "", "constexpr SpaceEmoji kSpaceEmoji[] = {",
        *[f"    {{{quote(emoji)}, {quote(name)}, {quote(words)}, {category}}},"
          for emoji, name, words, category in rows],
        "};", "",
    ]
    return "\n".join(lines), len(rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--chromium-src", required=True, type=Path)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    output = args.output or args.chromium_src / "chrome/browser/ui/helium/arcium_space_emoji_data.inc"
    data, count = generate(args.chromium_src)
    output.write_text(data)
    print(f"Generated {count} emoji in {output}")


if __name__ == "__main__":
    main()
